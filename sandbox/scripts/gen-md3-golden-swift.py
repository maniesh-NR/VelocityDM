#!/usr/bin/env python3
"""Generate the SwiftPM MD3 golden-literal test file (S12-mac2 spec rule 1.1/12).

Copies the 18-role subset values from the Rust-generated baseline JSON
(android/shared/src/jvmTest/resources/md3-tokens-baseline.json) into a
hardcoded XCTest table — the Swift-side tripwire the chain otherwise
lacks. Regenerate after any deliberate color-math change (Rust → Kotlin
→ BOTH Swift trees in the same commit, rule 12).
"""
import json

BASELINE = "android/shared/src/jvmTest/resources/md3-tokens-baseline.json"
OUT = "macos-swiftui/Tests/VelocityDMSwiftUIAppTests/Md3GoldenTests.swift"

ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
    "secondaryContainer", "onSecondaryContainer", "tertiary", "error",
    "surface", "surfaceContainerLowest", "surfaceContainerLow",
    "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
    "onSurface", "onSurfaceVariant", "outline", "outlineVariant",
]
# Swift Md3Scheme field names (lowerCamelCase first letter)
SWIFT_ROLES = [r[0].lower() + r[1:] for r in ROLES]

d = json.load(open(BASELINE))
lines = []
for s in d["seeds"]:
    for mode in ("light", "dark"):
        block = s[mode]
        vals = ",\n            ".join("%s: 0x%06X" % (f, block[r]) for f, r in zip(SWIFT_ROLES, ROLES))
        lines.append(
            '        Golden(seed: 0x%s, name: "%s", dark: %s, roles: Md3Scheme(dark: %s,\n            %s\n        )),'
            % (s["seedHex"], s["name"].replace('"', '\\"'), "true" if block["dark"] else "false", "true" if block["dark"] else "false", vals)
        )

TEMPLATE = r'''// VelocityDM SwiftUI frontend — MD3 golden-literal tests (XCTest).
//
// HARDCODED hex values copied from the Rust-generated baseline
// android/shared/src/jvmTest/resources/md3-tokens-baseline.json
// (provenance inside that file: generated by
// scripts/gen-md3-baseline.py running the Rust canonical engine, via
// `cargo run -p vdm-md3 --bin md3-tokens`). 8 seeds x light/dark x the
// 18-role honest subset (S12-mac2 rule 3) = 288 pinned values — the
// Swift-side drift tripwire for the copied Md3.swift math (rule 12:
// any color-math/seed change patches Rust -> Kotlin -> BOTH Swift
// trees in the SAME commit and regenerates this table with
// scripts/gen-md3-golden-swift.py).

import XCTest

@testable import VelocityDMSwiftUIApp

final class Md3GoldenTests: XCTestCase {
    private struct Golden {
        let seed: UInt32
        let name: String
        let dark: Bool
        let roles: Md3Scheme
    }

    private static let golden: [Golden] = [
@@GOLDEN_BLOCKS@@
    ]

    func testGoldenLiterals() {
        for g in Self.golden {
            let got = Md3Scheme.fromSeedHex(g.seed, dark: g.dark)
            let pairs: [(String, UInt32, UInt32)] = [
                ("primary", got.primary, g.roles.primary),
                ("onPrimary", got.onPrimary, g.roles.onPrimary),
                ("primaryContainer", got.primaryContainer, g.roles.primaryContainer),
                ("onPrimaryContainer", got.onPrimaryContainer, g.roles.onPrimaryContainer),
                ("secondaryContainer", got.secondaryContainer, g.roles.secondaryContainer),
                ("onSecondaryContainer", got.onSecondaryContainer, g.roles.onSecondaryContainer),
                ("tertiary", got.tertiary, g.roles.tertiary),
                ("error", got.error, g.roles.error),
                ("surface", got.surface, g.roles.surface),
                ("surfaceContainerLowest", got.surfaceContainerLowest, g.roles.surfaceContainerLowest),
                ("surfaceContainerLow", got.surfaceContainerLow, g.roles.surfaceContainerLow),
                ("surfaceContainer", got.surfaceContainer, g.roles.surfaceContainer),
                ("surfaceContainerHigh", got.surfaceContainerHigh, g.roles.surfaceContainerHigh),
                ("surfaceContainerHighest", got.surfaceContainerHighest, g.roles.surfaceContainerHighest),
                ("onSurface", got.onSurface, g.roles.onSurface),
                ("onSurfaceVariant", got.onSurfaceVariant, g.roles.onSurfaceVariant),
                ("outline", got.outline, g.roles.outline),
                ("outlineVariant", got.outlineVariant, g.roles.outlineVariant),
            ]
            for (role, actual, want) in pairs {
                XCTAssertEqual(
                    actual, want,
                    String(format: "seed %@ dark=%d role %@: 0x%06X != baseline 0x%06X",
                           g.name, g.dark ? 1 : 0, role, actual, want)
                )
            }
        }
    }

    func testGoldenTableShape() {
        // 8 seeds x light/dark — the full table, no dropped blocks.
        XCTAssertEqual(Self.golden.count, 16)
        XCTAssertEqual(Set(Self.golden.map { $0.seed }).count, 8)
        for seed in Set(Self.golden.map { $0.seed }) {
            let blocks = Self.golden.filter { $0.seed == seed }
            XCTAssertEqual(blocks.map { $0.dark }, [false, true])
        }
    }

    func testSeedListMatchesRustList() {
        // The 8-entry seed list must stay constants-identical to
        // vdm_md3::SEEDS (rule 3).
        XCTAssertEqual(Md3Seeds.count, 8)
        XCTAssertEqual(Md3DefaultSeed, 0x4156A4)
        XCTAssertEqual(Md3Seeds[0].0, 0x4156A4)
        XCTAssertEqual(Md3Seeds[1].0, 0x6750A4)
        XCTAssertEqual(Md3Seeds[2].0, 0x00639B)
        XCTAssertEqual(Md3Seeds[3].0, 0x006A6A)
        XCTAssertEqual(Md3Seeds[4].0, 0x386A33)
        XCTAssertEqual(Md3Seeds[5].0, 0x8F4C00)
        XCTAssertEqual(Md3Seeds[6].0, 0x984061)
        XCTAssertEqual(Md3Seeds[7].0, 0x56606F)
    }
}
'''

body = TEMPLATE.replace("@@GOLDEN_BLOCKS@@", "\n".join(lines))

with open(OUT, "w") as f:
    f.write(body)
print("wrote", OUT, "with", len(lines), "golden blocks")
