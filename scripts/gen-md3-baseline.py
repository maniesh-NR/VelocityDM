#!/usr/bin/env python3
"""Generate the Kotlin Md3-port drift-tripwire baseline.

Runs the Rust canonical engine (vdm-md3's `md3-tokens` CLI) for every
named seed, light + dark, and assembles
android/shared/src/commonTest/resources/md3-tokens-baseline.json.

The Kotlin port (android/shared commonMain Md3.kt) must reproduce every
value in this file — its golden test parses it. After any DELIBERATE
change to the color math, regenerate BOTH sides: this file (Rust truth)
and the Kotlin engine must stay in lock-step.

Usage (from the repo root):
  RUSTUP_HOME=/home/z/my-project/tools/rustup CARGO_HOME=/home/z/my-project/tools/cargo \
    python3 scripts/gen-md3-baseline.py
"""
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CLI = REPO / "target" / "debug" / "md3-tokens"
OUT = REPO / "android" / "shared" / "src" / "commonTest" / "resources" / "md3-tokens-baseline.json"

# (hex, name) — mirrors vdm_md3::SEEDS exactly.
SEEDS = [
    (0x4156A4, "Brand blue"),
    (0x6750A4, "Baseline purple"),
    (0x00639B, "Ocean"),
    (0x006A6A, "Teal"),
    (0x386A33, "Forest"),
    (0x8F4C00, "Sunset"),
    (0x984061, "Rose"),
    (0x56606F, "Slate"),
]


def camel(key: str) -> str:
    parts = key.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def main() -> int:
    if not CLI.exists():
        print("building md3-tokens ...", file=sys.stderr)
        r = subprocess.run(
            ["cargo", "build", "-p", "vdm-md3", "--bin", "md3-tokens"],
            cwd=REPO,
        )
        if r.returncode != 0:
            print("cargo build failed", file=sys.stderr)
            return 1

    seeds = []
    for hexval, name in SEEDS:
        entry = {"seedHex": f"{hexval:06X}", "name": name}
        for mode, dark in (("light", False), ("dark", True)):
            flag = "--dark" if dark else "--light"
            out = subprocess.run(
                [str(CLI), "--seed", f"{hexval:06X}", flag],
                capture_output=True, text=True, check=True,
            ).stdout
            scheme = json.loads(out)
            entry[mode] = {camel(k): v for k, v in scheme.items()}
        seeds.append(entry)

    doc = {
        "provenance": (
            "Generated by scripts/gen-md3-baseline.py running the Rust "
            "canonical engine (cargo run -p vdm-md3 --bin md3-tokens). "
            "The Kotlin Md3 port in android/shared must reproduce every "
            "value — this file is the Rust<->Kotlin drift tripwire. "
            "After any deliberate color-math change, regenerate this file "
            "and update the Kotlin port in the same commit."
        ),
        "seeds": seeds,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {OUT} ({len(seeds)} seeds x light+dark)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
