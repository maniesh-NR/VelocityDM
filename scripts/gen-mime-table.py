#!/usr/bin/env python3
"""Generate extensions/shared/mime-table.js from the Rust MIME table.

The Rust table (crates/vdm-core/src/mime.rs) is the single source of truth
(S11-i B8 gate condition); this script emits the JS copy the extension side
consumes. A drift test in vdm-core regenerates the comparison — run this
after any mime.rs change:

    python3 scripts/gen-mime-table.py
"""

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RUST_TABLE = REPO / "crates/vdm-core/src/mime.rs"
OUT = REPO / "extensions/shared/mime-table.js"

ENTRY = re.compile(r'\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"[\s,]*\)')


def parse_rust_table() -> list:
    text = RUST_TABLE.read_text(encoding="utf-8")
    m = re.search(r"const MIME_TABLE: &\[\(&str, &str\)\] = &\[(.*?)\];", text, re.S)
    if not m:
        sys.exit("cannot find MIME_TABLE in mime.rs")
    entries = [(a.replace('\\"', '"'), b.replace('\\"', '"')) for a, b in ENTRY.findall(m.group(1))]
    # strip compile-time comment-only noise defensively
    return [(a, b) for a, b in entries if a and b]


def main() -> None:
    table = parse_rust_table()
    if len(table) < 90:
        sys.exit(f"table suspiciously small ({len(table)} entries); refusing")
    obj = {a: b for a, b in table}  # insertion order preserved (3.7+)
    body = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "// Generated by scripts/gen-mime-table.py from the Rust MIME table\n"
        "// (crates/vdm-core/src/mime.rs) — the single source of truth (S11-i B8).\n"
        "// Do not edit; regenerate with: python3 scripts/gen-mime-table.py\n"
        "// UMD: loadable via importScripts (classic service worker), manifest\n"
        "// scripts (Firefox event pages), script tags, and node require().\n"
        "(function (root, factory) {\n"
        "  if (typeof module !== 'undefined' && module.exports) {\n"
        "    module.exports = factory();\n"
        "  } else {\n"
        "    root.VDMMimeTable = factory();\n"
        "  }\n"
        "})(typeof self !== 'undefined' ? self : this, function () {\n"
        "  'use strict';\n"
        f"  var MIME_TABLE = {body};\n"
        "\n"
        "  // Preferred extension for a MIME value, or null when unknown.\n"
        "  // Mirrors vdm_core::mime::extension_for_mime (parameters and case\n"
        "  // normalized away; never a guess).\n"
        "  function extensionForMime(mimeType) {\n"
        "    if (typeof mimeType !== 'string') return null;\n"
        "    var bare = mimeType.split(';')[0].trim().toLowerCase();\n"
        "    return Object.prototype.hasOwnProperty.call(MIME_TABLE, bare)\n"
        "      ? MIME_TABLE[bare]\n"
        "      : null;\n"
        "  }\n"
        "\n"
        "  return { MIME_TABLE: MIME_TABLE, extensionForMime: extensionForMime };\n"
        "});\n",
        encoding="utf-8",
    )
    print(f"{OUT}: {len(table)} entries")


if __name__ == "__main__":
    main()
